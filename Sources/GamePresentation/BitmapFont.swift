/// Original 5×7 bitmap font in a 6×8 cell (1 pixel padding right/bottom).
/// Covers ASCII 32..126 inclusive. Pure Swift, no platform dependencies.
public enum BitmapFont {
    /// Glyph cell width including 1px right padding.
    public static let glyphWidth: Int = 6
    /// Glyph cell height including 1px bottom padding.
    public static let glyphHeight: Int = 8

    /// Returns the 7 rows of bits for the given character (ASCII 32..126).
    /// Each row is a UInt8 where bit 7 = leftmost pixel, bit 1 = 5th pixel, bit 0 = padding (always 0).
    /// Returns the fallback box glyph (all pixels on) for unknown characters.
    public static func glyph(_ c: Character) -> [UInt8] {
        let idx = c.unicodeScalars.first?.value ?? 0
        guard idx >= 32 && idx <= 126 else { return fallbackGlyph }
        return glyphTable[Int(idx) - 32]
    }

    /// Returns the pixel width of a string (glyphWidth * count).
    public static func textWidth(_ s: String) -> Int {
        glyphWidth * s.count
    }

    /// Normalizes a string to ASCII 32..126 with documented fallbacks.
    /// Non-ASCII characters map to: ❤️/♡→"*", ⚡️/⚡→"!", ⚪️→"o", █→"#", ░→".",
    /// —→"-", ×→"x", ↓→"v", ←→"<", →→">", •→".", ↑→"^", …→"...", any other→"?".
    public static func normalize(_ s: String) -> String {
        var out = String()
        out.reserveCapacity(s.count)
        for ch in s {
            switch ch {
            case "❤️", "❤", "♥", "♡": out.append("*")
            case "⚡️", "⚡": out.append("!")
            case "⚪️", "⚪": out.append("o")
            case "█": out.append("#")
            case "░": out.append(".")
            case "—": out.append("-")
            case "×": out.append("x")
            case "↓": out.append("v")
            case "←": out.append("<")
            case "→": out.append(">")
            case "•": out.append(".")
            case "↑": out.append("^")
            case "…": out.append("...")
            default:
                if let scalar = ch.unicodeScalars.first,
                   ch.unicodeScalars.count == 1,
                   scalar.value >= 32 && scalar.value <= 126 {
                    out.append(ch)
                } else {
                    out.append("?")
                }
            }
        }
        return out
    }

